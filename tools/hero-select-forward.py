# Hero select forward poses (t389u). Builds, from the approved sprite-bot art (/workspace/audit/heroselect-art-*,
# Joseph "Send it", Nov 1 2026) and its working masks (/workspace/audit/hs/mask_sb_*.png):
#   public/ui/hero-forward/<id>.webp        the hero's forward-pose cutout (tight PNG, standing scale, WebP q92)
#   public/ui/hero-forward/<id>-plate.webp  a clean plate (standing figure inpainted out, feathered alpha) that hides
#                                           the standing figure while the forward pose is shown
#   src/game/heroSelectArt.ts               placement table (base px) generated from heroselect-art-forward-anchors.json
# The Sorceress cutout's baked bolt is keyed out: the game draws her lightning live on the canvas.
# Needs opencv-python-headless, numpy, Pillow. Usage: python tools/hero-select-forward.py [/workspace/audit]
import sys, json, numpy as np, cv2
from PIL import Image
ART = sys.argv[1] if len(sys.argv) > 1 else '/workspace/audit'
OUT = 'public/ui/hero-forward'
PLATE_SCALE = 0.6  # same density as the 1920 px backdrop (3200 px source)
anch = json.load(open(f'{ART}/heroselect-art-forward-anchors.json'))
# t389u polish: the plates come from the edge colour-matched base that hero-select-bg.py pastes into the backdrop
# (heroselect-art-base-matched.png, written by it), so they match the frame exactly; run hero-select-bg.py first.
import os
_bp = f'{ART}/heroselect-art-base-matched.png'
base = np.asarray(Image.open(_bp if os.path.exists(_bp) else f'{ART}/heroselect-art-base.png').convert('RGB'))
H, W = base.shape[:2]
t = 1424 / 1024
# mask crops and their boxes (in 1024-wide units of the base) as used for the mock-ups (hs/build2.py)
B = {'amazon': ('amazon', (0, 45)), 'assassin': ('assassin', (185, 65)), 'necromancer': ('necro', (315, 45)),
     'barbarian': ('barb', (440, 30)), 'paladin': ('pal', (565, 45)), 'sorceress': ('sorc', (735, 50)),
     'druid': ('druid', (885, 35))}
rows = []
for hero, (mk, (bx, by)) in B.items():
    a = anch[hero]
    # forward cutout
    tight = Image.open(f'{ART}/heroselect-art-{hero}-forward-tight.png').convert('RGBA')
    if hero == 'sorceress':
        px = np.asarray(tight).copy(); r, g, b, al = [px[..., i].astype(int) for i in range(4)]
        yy, xx = np.mgrid[0:px.shape[0], 0:px.shape[1]]
        bolt = (yy < 66) & (b >= r - 4) & (b > 70)
        hand = (xx > 150) & (yy > 34) & ~((b > r + 25) & (b > 180))
        kill = cv2.dilate((bolt & ~hand).astype(np.uint8), np.ones((3, 3), np.uint8)) > 0
        kill &= ~((r > b + 8) & (yy > 40))  # never the staff head or skin
        px[..., 3][kill] = 0
        tight = Image.fromarray(px)
    tight.save(f'{OUT}/{hero}.webp', quality=92, alpha_quality=100, method=6)
    # clean plate
    m = np.zeros((H, W), np.uint8)
    mm = np.asarray(Image.open(f'{ART}/hs/mask_sb_{mk}.png'))
    X, Y = int(bx * t), int(by * t); m[Y:Y + mm.shape[0], X:X + mm.shape[1]] = mm
    if hero == 'paladin': cv2.line(m, (790, 330), (875, 262), 255, 7)  # lowered sword
    if hero == 'amazon': cv2.line(m, (0, 240), (215, 395), 255, 7)  # lowered spear
    md = cv2.dilate((m > 40).astype(np.uint8) * 255, np.ones((9, 9), np.uint8))
    plate = cv2.inpaint(np.ascontiguousarray(base[..., ::-1]), md, 6, cv2.INPAINT_TELEA)[..., ::-1]
    alpha = cv2.GaussianBlur(cv2.dilate(md, np.ones((7, 7), np.uint8)), (0, 0), 3)
    ys, xs = np.where(alpha > 2)
    x0, y0, x1, y1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
    rgba = np.dstack([plate[y0:y1, x0:x1], alpha[y0:y1, x0:x1]])
    im = Image.fromarray(rgba, 'RGBA')
    im = im.resize((max(1, round(im.size[0] * PLATE_SCALE)), max(1, round(im.size[1] * PLATE_SCALE))), Image.LANCZOS)
    im.save(f'{OUT}/{hero}-plate.webp', quality=88, alpha_quality=90, method=6)
    ox, oy = a['tight_png_offset_in_base_xy']; tw, th = a['tight_png_size_wh']
    rows.append(f"  {hero}: {{ feet: [{a['standing_feet_xy'][0]}, {a['standing_feet_xy'][1]}], forward: [{ox}, {oy}, {tw}, {th}], plate: [{x0}, {y0}, {x1 - x0}, {y1 - y0}] }},")
fs = anch['_forward_step']
ts = f"""// Generated by tools/hero-select-forward.py from heroselect-art-forward-anchors.json (t389u). Do not edit by hand.
/** Standing-back base and forward layers are in base px (1424x587); see HERO_BASE in heroSelect.ts for the frame. */
export const FORWARD_STEP = {{ scale: {fs['scale']}, dy: {fs['dy_px']} }} as const;
export interface HeroArt {{
  /** Standing feet (pivot of the forward step), base px. */
  feet: readonly [number, number];
  /** Forward-pose cutout box at standing scale (x, y, w, h), base px: public/ui/hero-forward/<id>.webp. */
  forward: readonly [number, number, number, number];
  /** Clean plate box (x, y, w, h), base px: public/ui/hero-forward/<id>-plate.webp hides the standing figure. */
  plate: readonly [number, number, number, number];
}}
export const HERO_ART_LAYERS: Readonly<Record<string, HeroArt>> = {{
{chr(10).join(rows)}
}};
"""
open('src/game/heroSelectArt.ts', 'w').write(ts)
print(ts)
